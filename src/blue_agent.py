class BlueAgent:
    def __init__(self, model_path: str = None):

        # fallback словарь (основная логика сейчас)
    
        self.sus_keywords = [
        # срочность / давление
        "срочно", "немедленно", "прямо сейчас", "без промедления",
        "сейчас же", "незамедлительно", "быстро", "оперативно",

        # угрозы / последствия
        "угроза", "опасность", "внимание", "критично", "критический",
        "последствия", "наказание", "штраф", "блокировка", "удаление",
        "отключение", "потеря", "сломано", "повреждение",

        # взлом / безопасность
        "взлом", "взломан", "вирус", "троян", "вредоносный",
        "подозрительный", "подозрение", "утечка", "данные",
        "пароль", "аккаунт", "доступ", "авторизация",
        "проверка", "подтверждение", "верификация",

        # манипуляция / давление
        "должен", "обязан", "нельзя отказаться", "нет выбора",
        "последний шанс", "единственный шанс", "иначе",
        "пожалеешь", "пожалеете", "рискуешь", "ошибка",
        "не упусти", "сделай сейчас", "прими решение",
        "не откладывай", "без вопросов", "без обсуждения",

        # фишинг / социальная инженерия
        "подтверди", "подтверждение", "войти", "вход",
        "ссылка", "перейди", "скачай", "установи",
        "обнови", "обновление", "активируй", "активация",
        "проверить", "проверка безопасности", "служба поддержки",

        # эмоц. давление
        "страшно", "опасно", "паника", "экстренно",
        "важно", "очень важно", "крайне важно",
        "не игнорируй", "не игнорировать"
    ]

    def analyze(self, messages):

        joined = " ".join(messages).lower()

        found_words = []

        for w in self.sus_keywords:
            if w in joined:
                found_words.append(w)

        # риск = доля найденных слов
        risk = len(found_words) / len(self.sus_keywords)

        return {
            "sus_words": found_words,
            "risk": min(1.0, risk)
        }